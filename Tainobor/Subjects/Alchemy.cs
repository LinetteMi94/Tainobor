                               "но для первого занятия вполне сойдёт. Продолжай практиковаться, и скоро нож будет тебя слушаться!»");
                break;
            case LessonGrade.Хорошо:
                Messages.Print("Лукьян наклоняется над разделочной доской, поправляет очки и улыбается.\n" +
                               "«Вот это уже хороший результат! Кусочки почти одинаковые, срезы аккуратные. " +
                               "Видно, что ты не торопился и следил за каждым движением. Так держать!»");
                player.IncreaseCharacteristic(Characteristics.Ловкость,1);
                break;
            case LessonGrade.Превосходно:
                Messages.Print("Лукьян некоторое время молча рассматривает нарезанный корень, а затем довольно потирает руки.\n" +
                               "«Превосходно! Именно такой нарезки я и ждал. Ровные кусочки, чистые срезы, " +
                               "ни одного лишнего движения... Погодите, а что будет, если нарезать их ещё тоньше?.. " +
                               "Нет-нет, это мы проверим в другой раз! Замечательная работа!»");
                player.IncreaseCharacteristic(Characteristics.Ловкость,2);
                break;
        }
        Messages.Print($"Ваша оценка {grade}");
        Messages.Print("Вы собираете вещи и выходите из кабинета алхимии");
        Messages.Key();
    }

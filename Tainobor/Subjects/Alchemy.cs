        Messages.Print("Вы входите в кабинет алхимии.");
        Messages.Print("Лукьян Берест подходит к столу и оглядывает первокурсников.\n");
        Messages.Print("— Добро пожаловать на алхимию! Меня зовут Лукьян Берест. В этом году мы с вами узнаем, " +
                       "как устроены вещества, почему они взаимодействуют друг с другом и можно ли сделать " +
                       "хороший рецепт ещё лучше.\n");
        Messages.Print("Он достаёт из кармана небольшой клочок бумаги, " +

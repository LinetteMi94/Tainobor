                       "Алхимик понимает, что именно он туда кладёт.\n"); 
        Messages.Print("— У каждого ингредиента есть свои свойства. Одни вещества могут " +
                       "усиливать действие других, другие — ослаблять его, а некоторые " +
                       "при смешивании дают совершенно неожиданный результат.\n");
        Messages.Print("Лукьян берёт со стола небольшой высушенный корень и показывает его ученикам.\n");
        Messages.Print("— Возьмём, к примеру, вот этот корень. Пока он лежит перед нами, " +
                       "он остаётся тем же растением. Но стоит начать его обрабатывать, " +
                       "как мы уже вмешиваемся в процесс приготовления состава.\n");
        Messages.Print("— Измельчение помогает подготовить ингредиент к дальнейшему использованию. " +
                       "Но здесь есть тонкость: важно не только то, что мы делаем, " +

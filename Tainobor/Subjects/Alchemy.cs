                       "пытаясь сделать кусочки одинаковыми.");
        var grade = AssessResult(player, Characteristics.Ловкость);
        switch (grade)
        {
            case LessonGrade.Неудача:
                Messages.Print("Лукьян вздыхает и осторожно отодвигает нож от твоей руки.\n" +
                               "«Так, так... Пожалуй, пока остановимся. Корень нарезан слишком неровно, " +
                               "а некоторые кусочки и вовсе превратились в крошку. Ничего страшного, " +
                               "но нам придётся немного потренироваться после занятий. Уверен, в следующий раз получится лучше!»");
                break;
            case LessonGrade.Удовлетворительно:
                Messages.Print("Лукьян внимательно осматривает нарезанный корень и одобрительно кивает.\n" +

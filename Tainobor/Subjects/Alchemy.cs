        Messages.Print("— Не торопитесь. Здесь важнее точность, чем скорость. " +
                       "И, пожалуйста, держите пальцы подальше от лезвия. " +
                       "Мне бы очень не хотелось начинать учебный год с визита к целителям.\n");

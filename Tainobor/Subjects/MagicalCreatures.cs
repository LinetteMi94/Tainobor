    private void Lesson1(Player player)
    {
        Console.Clear();
        Messages.Print("Вы входите в кабинет звероведения.");
        Messages.Print("Ярослава Клык заходит к столу и смотрит на класс.\n");
        Messages.Print("— Здравствуйте, ученики! Меня зовут Ярослава Клык. " +
                       "В этом году я буду преподавать вам звероведение.\n");
        Messages.Print("— Прежде чем мы начнём изучать отдельных представителей магического мира, " +
                       "необходимо разобраться, какими они бывают и на какие группы делятся.\n");
        Messages.Print("— Магических существ принято классифицировать по их способностям и особенностям.\n");
        Messages.Print("Целительные — способны исцелять раны, восстанавливать силы и помогать при различных недугах.\n");
        Messages.Print("Разумные — обладают развитым интеллектом, могут понимать человеческую речь, " +
                       "разговаривать и даже самостоятельно применять магию.\n"); 
        Messages.Print("Стихийные — связаны с природными стихиями и способны помогать " +
                       "магам-стихийникам управлять своей силой.\n");
        Messages.Print("Иллюзорные — создают обманчивые образы, влияют на восприятие окружающих " +
                       "и могут скрывать свою истинную внешность.\n");
        Messages.Print("Защитные — умеют создавать магические барьеры, отражать атаки и оберегать других существ.\n");
        Messages.Print("Хранители — охраняют определённые места, предметы или древние тайны. " +
                       "Нередко их существование тесно связано с тем, что они защищают.\n");
        Messages.Print("Смертельно опасные — представляют серьёзную угрозу для жизни. " +
                       "Встреча с ними требует особой подготовки.\n");
        Messages.Print("— Обратите внимание: одна категория не исключает другую. " +
                       "Некоторые существа обладают сразу несколькими особенностями.\n");
        Messages.Print("Ярослава замолкает и достаёт из шкафа несколько карточек " +
                       "с описаниями неизвестных существ.\n");
        Messages.Print("— Сейчас у каждого из вас есть по три карточки. Ваша задача определить" +
                       " к каким категориям относится каждое существо.\n");
        Messages.Print("Не торопитесь с ответами. В звероведении важно не только знать " +
                       "названия существ, но и уметь замечать особенности их поведения. " +
                       "Именно этому мы с вами и будем учиться.\n");
        Console.ReadKey();
        Messages.Print("Вы смотрите на карточки перед вами и пытаетесь вспомнить, " +
                       "что услышали сейчас на лекции\n");
        player.StartTest(QuestionsLesson1);
        var grade =  AssessResult(player, Characteristics.Ловкость, 3 ,5 ,7);
        switch (grade)
        {
            case LessonGrade.Неудача:
                Messages.Print("Лукьян вздыхает и осторожно отодвигает нож от твоей руки.\n" +
                               "«Так, так... Пожалуй, пока остановимся. Корень нарезан слишком неровно, " +
                               "а некоторые кусочки и вовсе превратились в крошку. Ничего страшного, " +
                               "но нам придётся немного потренироваться после занятий. Уверен, в следующий раз получится лучше!»");
                break;
            case LessonGrade.Удовлетворительно:
                Messages.Print("Лукьян внимательно осматривает нарезанный корень и одобрительно кивает.\n" +
                               "«Уже неплохо! Конечно, некоторые кусочки великоваты, а другие могли бы быть ровнее, " +
                               "но для первого занятия вполне сойдёт. Продолжай практиковаться, и скоро нож будет тебя слушаться!»");
                break;
            case LessonGrade.Хорошо:
                Messages.Print("Лукьян наклоняется над разделочной доской, поправляет очки и улыбается.\n" +
                               "«Вот это уже хороший результат! Кусочки почти одинаковые, срезы аккуратные. " +
                               "Видно, что ты не торопился и следил за каждым движением. Так держать!»");
                player.IncreaseCharacteristic(Characteristics.Ловкость,1);
                break;
            case LessonGrade.Превосходно:
                Messages.Print("Лукьян некоторое время молча рассматривает нарезанный корень, а затем довольно потирает руки.\n" +
                               "«Превосходно! Именно такой нарезки я и ждал. Ровные кусочки, чистые срезы, " +
                               "ни одного лишнего движения... Погодите, а что будет, если нарезать их ещё тоньше?.. " +
                               "Нет-нет, это мы проверим в другой раз! Замечательная работа!»");
                player.IncreaseCharacteristic(Characteristics.Ловкость,2);
                break;
        }
        Messages.Print($"Ваша оценка {grade}");
        Messages.Print("Вы берёте сумку и выходите из кабинета звероведения");
        Messages.Key();
    }
   
